void usDelay(uint32_t uSec)
{
	TIM7->ARR = uSec * 2 - 1; // Configure update event to count up to desired uSec
	TIM7->EGR = 1; // Clear timer and prescaler counters
	TIM7->SR &= ~1; // Clear update register
	TIM7->CR1 |= 1; // Enable the counter
	while ((TIM7->SR & 0x1) != 1) ;
	TIM7->SR &= ~ 1;
}

void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
	if (htim->Instance == TIM2 && htim->Channel == HAL_TIM_ACTIVE_CHANNEL_3)
	{
		if (ultraCaptureState == 0)
		{
			ultraRisingTime = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_3);
			ultraCaptureState = 1;
		}
		else if (ultraCaptureState == 1)
		{
			ultraFallingTime = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_3);
			ultraCaptureState = 0;
			icFlag = 1;
		}
	}
}

